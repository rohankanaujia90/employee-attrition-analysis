-- =====================================================================
-- Employee Attrition Analysis | 01_ddl.sql
-- Creates the staging table and the star schema (Oracle 12c+ / XE 21c).
-- Safe to re-run: drops existing tables first.
-- =====================================================================

BEGIN
    FOR t IN (
        SELECT table_name FROM user_tables
        WHERE table_name IN ('FACT_EMPLOYEE', 'DIM_DEPARTMENT', 'DIM_JOB_ROLE',
                             'DIM_EDUCATION_FIELD', 'STG_HR_EMPLOYEE')
    ) LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
    END LOOP;
END;
/

-- ---------------------------------------------------------------------
-- Staging: same column order as data/clean/hr_attrition_clean.csv
-- ---------------------------------------------------------------------
CREATE TABLE stg_hr_employee (
    employee_number            NUMBER,
    age                        NUMBER,
    age_band                   VARCHAR2(10),
    gender                     VARCHAR2(10),
    marital_status             VARCHAR2(20),
    department                 VARCHAR2(50),
    job_role                   VARCHAR2(50),
    job_level                  NUMBER,
    education                  NUMBER,
    education_field            VARCHAR2(50),
    business_travel            VARCHAR2(30),
    distance_from_home         NUMBER,
    overtime                   VARCHAR2(5),
    monthly_income             NUMBER,
    salary_band                VARCHAR2(10),
    percent_salary_hike        NUMBER,
    stock_option_level         NUMBER,
    total_working_years        NUMBER,
    years_at_company           NUMBER,
    tenure_band                VARCHAR2(10),
    years_in_current_role      NUMBER,
    years_since_last_promotion NUMBER,
    years_with_curr_manager    NUMBER,
    num_companies_worked       NUMBER,
    training_times_last_year   NUMBER,
    environment_satisfaction   NUMBER,
    job_satisfaction           NUMBER,
    relationship_satisfaction  NUMBER,
    work_life_balance          NUMBER,
    job_involvement            NUMBER,
    performance_rating         NUMBER,
    attrition                  VARCHAR2(5),
    attrition_flag             NUMBER(1),
    income_outlier_flag        NUMBER(1)
);

-- ---------------------------------------------------------------------
-- Dimensions
-- ---------------------------------------------------------------------
CREATE TABLE dim_department (
    dept_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dept_name  VARCHAR2(50) NOT NULL CONSTRAINT uq_dept_name UNIQUE
);

CREATE TABLE dim_job_role (
    role_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_name  VARCHAR2(50) NOT NULL CONSTRAINT uq_role_name UNIQUE
);

CREATE TABLE dim_education_field (
    edu_field_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    edu_field_name  VARCHAR2(50) NOT NULL CONSTRAINT uq_edu_field_name UNIQUE
);

-- ---------------------------------------------------------------------
-- Fact: one row per employee
-- ---------------------------------------------------------------------
CREATE TABLE fact_employee (
    employee_id                NUMBER PRIMARY KEY,
    dept_id                    NUMBER NOT NULL REFERENCES dim_department (dept_id),
    role_id                    NUMBER NOT NULL REFERENCES dim_job_role (role_id),
    edu_field_id               NUMBER REFERENCES dim_education_field (edu_field_id),
    age                        NUMBER(3),
    age_band                   VARCHAR2(10),
    gender                     VARCHAR2(10),
    marital_status             VARCHAR2(20),
    job_level                  NUMBER(1),
    education                  NUMBER(1),
    business_travel            VARCHAR2(30),
    distance_from_home         NUMBER(3),
    overtime                   VARCHAR2(5),
    monthly_income             NUMBER(10, 2),
    salary_band                VARCHAR2(10),
    percent_salary_hike        NUMBER(3),
    stock_option_level         NUMBER(1),
    total_working_years        NUMBER(3),
    years_at_company           NUMBER(3),
    tenure_band                VARCHAR2(10),
    years_in_current_role      NUMBER(3),
    years_since_last_promotion NUMBER(3),
    years_with_curr_manager    NUMBER(3),
    num_companies_worked       NUMBER(3),
    training_times_last_year   NUMBER(3),
    environment_satisfaction   NUMBER(1),
    job_satisfaction           NUMBER(1),
    relationship_satisfaction  NUMBER(1),
    work_life_balance          NUMBER(1),
    job_involvement            NUMBER(1),
    performance_rating         NUMBER(1),
    attrition                  VARCHAR2(5) NOT NULL,
    attrition_flag             NUMBER(1)   NOT NULL,
    income_outlier_flag        NUMBER(1)   DEFAULT 0,
    CONSTRAINT ck_attrition      CHECK (attrition IN ('Yes', 'No')),
    CONSTRAINT ck_attrition_flag CHECK (attrition_flag IN (0, 1)),
    CONSTRAINT ck_flag_matches   CHECK ((attrition = 'Yes' AND attrition_flag = 1)
                                     OR (attrition = 'No'  AND attrition_flag = 0))
);

CREATE INDEX ix_fact_dept   ON fact_employee (dept_id);
CREATE INDEX ix_fact_role   ON fact_employee (role_id);
CREATE INDEX ix_fact_tenure ON fact_employee (tenure_band);
